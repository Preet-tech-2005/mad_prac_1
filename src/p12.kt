fun main() {

    val i = 10000

    val j: Double = i.toDouble()

    println("Integer value:" + i)
    println("Double value:" + j)

    val st = "10"

    val k: Int = st.toInt()

    println("String value: " + st)
    println("Integer value: " + k)

    val s = "20.21"

    val n: Double = st.toDouble()

    println("Integer value:" + s)
    println("Double value:" + n)
}